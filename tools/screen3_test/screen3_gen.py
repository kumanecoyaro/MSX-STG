"""SCREEN3(Multicolor)画像表示テスト用ROM(2026-09-12、"では取り敢えず
組み込みはせずテストをする...この画像を表示してみてくれ 表示テスト用の
ROMを作る ベースはタイトル表示までを流用 それ以外は空でいい"に対する
実機フィードバック"おｋ意図通り表示できた 次はこの6枚を連続で表示
3回繰り返して"で6枚のスライドショーへ拡張、さらに"6枚目こうなって
るんだけど これで正しいのか"→切り分け用のImage06単体テストで
"画像は正しく表示された てかこの6枚で16KBこえるのか?"という実機
フィードバックを受け、RLE圧縮でバンク跨ぎを完全に回避する方式へ変更)。

添付BSAVE形式ダンプ(01.SC3〜06.SC3、いずれもstart=0000h/end=203Fh/
payload8256byte、全6枚とも同一レイアウトと実測確認済み)の実バイトを
調査した結果、この特定ファイル群の内部レイアウトは"標準的なBASIC
SCREEN3デフォルト"(パターンジェネレータ0000h/ネームテーブル1800h)とは
異なり、詰めて保存されていると判明した:

  0000h-07FFh (2048byte): パターンジェネレータ(実絵柄データ、非ゼロ・
                           高エントロピー)
  0800h-0AFFh (768byte) : ネームテーブル(実測: 0,1,2,...,31を32byte
                           周期で4回繰り返し→32,33,...,63を4回→...という
                           規則的なランプ - "name = 32*(row_of_name//4)
                           +col"という機械的な割り当て、TMS9918
                           マルチカラーモードの仕様(1パターンあたり
                           8byteの割り当てのうち、row_of_name%4で
                           選ぶペア×Y&4の上下半分=8通りをフルに使う
                           ため、同じ4行グループ内は同じname値で
                           構わない)と正確に整合)
  0B00h以降              : 同じランプの続き(絵とは無関係な後続データ、
                           未使用)

6枚分の生データ(2816byte x6=16896byte)は16KBの1バンクに収まらず
0x8000をまたぐ - 実機フィードバックでASCII16バンク切替を試みたが
改善せず("変わってないな")、切り分けの結果Image06単体(バンク跨ぎ無し)
は正常表示されたため、データ自体・バンク切替そのものではなく「16KBを
超える」こと自体を避ける方が確実と判断。tools/title_screen/
title_bg_gen.pyと全く同じ自前RLE圧縮(PGT・NAMEをそれぞれ個別に圧縮、
合計16896byte→12287byte=72.7%)を適用し、6枚まとめてComb同様の1バンク
(16KB)に余裕で収まるようにした(バンク切替自体が完全に不要になる)。
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ASSETS = os.path.join(HERE, "assets")

PGT_LEN = 0x0800   # 2048 bytes - pattern generator (standard SCREEN1/3 size)
NAME_LEN = 0x0300  # 768 bytes - name table (32x24)
NAME_SRC_OFFSET = 0x0800  # where these files actually pack the name table

IMAGE_COUNT = 6

sys.path.insert(0, os.path.join(HERE, "..", "title_screen"))
import title_bg_gen  # noqa: E402  (汎用: rle_encode/rle_decode)


def load_payload(index):
    """index: 1-6."""
    path = os.path.join(ASSETS, f"Image{index:02d}.SC3")
    with open(path, "rb") as f:
        data = f.read()
    assert data[0] == 0xFE, f"{path}: not a BSAVE-format file (marker byte was {data[0]:02X}h)"
    start = data[1] | (data[2] << 8)
    assert start == 0x0000, f"{path}: expected VRAM start 0000h, got {start:04X}h"
    payload = data[7:]
    assert len(payload) >= NAME_SRC_OFFSET + NAME_LEN, \
        f"{path}: payload too short ({len(payload)} bytes) to contain the name table at {NAME_SRC_OFFSET:04X}h"
    return payload


def pattern_generator(index):
    return load_payload(index)[0:PGT_LEN]


def name_table(index):
    return load_payload(index)[NAME_SRC_OFFSET:NAME_SRC_OFFSET + NAME_LEN]


def db_bytes(byte_list, per_line=16):
    lines = []
    for i in range(0, len(byte_list), per_line):
        chunk = byte_list[i:i + per_line]
        lines.append("    DB " + ",".join(str(b) for b in chunk))
    return "\n".join(lines)


def emit_asm_tables():
    out = ["; ===== SCREEN3 slideshow images (Image01-06.SC3), RLE-compressed "
           "(tools/title_screen/title_bg_gen.py's codec) - generated by screen3_gen.py, "
           "do not hand-edit ====="]
    for i in range(1, IMAGE_COUNT + 1):
        pgt = pattern_generator(i)
        name = name_table(i)
        pgt_c, pgt_segs = title_bg_gen.rle_encode(pgt)
        name_c, name_segs = title_bg_gen.rle_encode(name)
        assert title_bg_gen.rle_decode(pgt_c, pgt_segs) == pgt, f"image{i}: PGT RLE round-trip mismatch"
        assert title_bg_gen.rle_decode(name_c, name_segs) == name, f"image{i}: NAME RLE round-trip mismatch"
        out.append(f"SC3_IMG{i}_PGT_RLE:")
        out.append(db_bytes(list(pgt_c)))
        out.append(f"SC3_IMG{i}_PGT_SEGMENTS EQU {pgt_segs}")
        out.append(f"SC3_IMG{i}_NAME_RLE:")
        out.append(db_bytes(list(name_c)))
        out.append(f"SC3_IMG{i}_NAME_SEGMENTS EQU {name_segs}")
    return "\n".join(out)


if __name__ == "__main__":
    total_raw = 0
    total_c = 0
    for i in range(1, IMAGE_COUNT + 1):
        pgt = pattern_generator(i)
        name = name_table(i)
        pgt_c, pgt_segs = title_bg_gen.rle_encode(pgt)
        name_c, name_segs = title_bg_gen.rle_encode(name)
        print(f"Image{i:02d}.SC3: PGT {len(pgt)}->{len(pgt_c)}B({pgt_segs}seg) "
              f"NAME {len(name)}->{len(name_c)}B({name_segs}seg)")
        total_raw += len(pgt) + len(name)
        total_c += len(pgt_c) + len(name_c)
    print(f"TOTAL: {total_raw} -> {total_c} bytes ({100*total_c/total_raw:.1f}%)")
