GLYPHS = {**_GLYPHS_ATTACHED, **_GLYPHS_NEW}


def glyph_bytes(ch):
    rows = GLYPHS[ch]
    assert len(rows) == 8 and all(len(r) == 8 for r in rows)
    out = []
    for row in rows:
        b = 0
        for i, c in enumerate(row):
            if c == "1":
                b |= 0x80 >> i
        out.append(b)
    return out


def db_bytes(values, per_line=8):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("    DB " + ",".join(str(v) for v in values[i:i + per_line]))
    return "\n".join(lines)


def font_block_bytes(chars):
    """指定した文字順に並べた連続ビットマップ(8byte/文字)を返す。"""
    out = []
    for ch in chars:
        out.extend(glyph_bytes(ch))
    return out


